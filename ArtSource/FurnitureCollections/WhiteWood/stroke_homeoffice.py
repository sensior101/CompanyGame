def pixels(d,pts,r=7,view='Front'):
 out=np.zeros(len(d['faces']),bool);v=d[view];uv=np.c_[v[:,0]*900,(1-v[:,1])*900]
 # Orthographic camera projection is affine. Ray-pick actual triangles, including
 # large panels whose centroid is far from the paint stroke.
 P=np.linalg.lstsq(np.c_[d['centers'],np.ones(len(v))],v,rcond=None)[0]
 vv=np.c_[d['vertices'],np.ones(len(d['vertices']))]@P; tri=vv[d['faces']];a=tri[:,0,:2];u=tri[:,1,:2]-a;w=tri[:,2,:2]-a;den=u[:,0]*w[:,1]-u[:,1]*w[:,0];safe=np.where(abs(den)>1e-12,den,1)
 for x,y in pts:
  point=np.array([x/900,1-y/900]);p=point-a;bb=(p[:,0]*w[:,1]-p[:,1]*w[:,0])/safe;cc=(u[:,0]*p[:,1]-u[:,1]*p[:,0])/safe;inside=(abs(den)>1e-12)&(bb>=0)&(cc>=0)&(bb+cc<=1)
  sel=np.linalg.norm(uv-[x,y],axis=1)<r
  if np.any(inside):
   depth=tri[:,0,2]+bb*(tri[:,1,2]-tri[:,0,2])+cc*(tri[:,2,2]-tri[:,0,2]);ids=np.flatnonzero(inside);i=ids[np.argmin(depth[ids])];out[i]=True;out|=sel&(abs(v[:,2]-depth[i])<.01)
  elif np.any(sel):out|=sel&(v[:,2]<v[sel,2].min()+.008)
 return out
